[[nodiscard]] inline int16_t decodeG711UlawSample(uint8_t u) {
	u = static_cast<uint8_t>(~u);
	const int sign = u & 0x80;
	const int exponent = (u >> 4) & 0x07;
	const int mantissa = u & 0x0F;
	int sample = (((mantissa << 3) + 0x84) << exponent) - 0x84;
	if (sign != 0) {
		sample = -sample;
	}
	return static_cast<int16_t>(sample);
}

[[nodiscard]] inline std::vector<int16_t> decodeSpeechProbePcm16k() {
	const size_t n8 = kSpeechProbeUlaw8k.size();
	std::vector<int16_t> pcm16k;
	pcm16k.reserve(n8 * 2);
	for (size_t i = 0; i < n8; ++i) {
		const int16_t s0 = decodeG711UlawSample(kSpeechProbeUlaw8k[i]);
		const int16_t s1 = (i + 1 < n8) ? decodeG711UlawSample(kSpeechProbeUlaw8k[i + 1]) : s0;
		pcm16k.push_back(s0);
		pcm16k.push_back(static_cast<int16_t>((static_cast<int32_t>(s0) + static_cast<int32_t>(s1)) / 2));
	}
	return pcm16k;
}

